#!/usr/bin/env node
/**
 * Build the phone / web version of BLAM (an installable, offline-capable PWA) into dist-web/.
 *
 *   node scripts/build-web.js            -> dist-web/app/
 *   PWA_SLUG=k7q2x9m4 node scripts/...  -> dist-web/k7q2x9m4/   (an unlisted address)
 *
 * The app is the same renderer the desktop app uses (src/renderer). Data lives only on the
 * device (IndexedDB); the site just serves static files.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const pkg = require(path.join(root, 'package.json'));
const slug = String(process.env.PWA_SLUG || 'app').trim().replace(/[^a-zA-Z0-9_-]/g, '') || 'app';
const outRoot = path.join(root, 'dist-web');
const out = path.join(outRoot, slug);

fs.rmSync(outRoot, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
fs.cpSync(path.join(root, 'src/renderer'), out, { recursive: true });
fs.cpSync(path.join(root, 'src/web/icons'), path.join(out, 'icons'), { recursive: true });
fs.copyFileSync(path.join(root, 'src/web/pwa.js'), path.join(out, 'js/pwa.js'));

// index.html: manifest, iOS home-screen metadata, version, PWA bootstrap.
const htmlFile = path.join(out, 'index.html');
let html = fs.readFileSync(htmlFile, 'utf8');
html = html.replace('<link rel="stylesheet" href="css/app.css">', [
  '<link rel="stylesheet" href="css/app.css">',
  '  <link rel="manifest" href="manifest.webmanifest">',
  '  <link rel="icon" href="icons/icon-192.png">',
  '  <link rel="apple-touch-icon" href="icons/apple-touch-icon.png">',
  '  <meta name="apple-mobile-web-app-capable" content="yes">',
  '  <meta name="mobile-web-app-capable" content="yes">',
  '  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">',
  '  <meta name="apple-mobile-web-app-title" content="BLAM">',
  '  <meta name="robots" content="noindex, nofollow">',
].join('\n'));
html = html.replace('<script src="js/util.js"></script>', `<script src="js/version.js"></script>\n  <script src="js/util.js"></script>`);
html = html.replace('<script src="js/app.js"></script>', '<script src="js/app.js"></script>\n  <script src="js/pwa.js"></script>');
fs.writeFileSync(htmlFile, html);
fs.writeFileSync(path.join(out, 'js/version.js'), `window.BLAM_WEB_VERSION = ${JSON.stringify(pkg.version)};\n`);

fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify({
  name: 'BLAM — Bitcoin Labz Asset Manager',
  short_name: 'BLAM',
  description: 'Private, local-first personal finance: crypto, stocks, real estate, loans, budgets and more.',
  id: './',
  start_url: './',
  scope: './',
  display: 'standalone',
  orientation: 'portrait',
  background_color: '#080b12',
  theme_color: '#080b12',
  categories: ['finance', 'productivity'],
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2));

// Service worker: precache every file; the cache name changes whenever any file changes.
const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p); else files.push(path.relative(out, p).split(path.sep).join('/'));
  }
})(out);
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(out, f)));
const cacheName = `blam-${pkg.version}-${hash.digest('hex').slice(0, 10)}`;
const precache = ['./', ...files.filter((f) => f !== 'sw.js')];
fs.writeFileSync(path.join(out, 'sw.js'), `/* BLAM service worker (generated by scripts/build-web.js) */
'use strict';
const CACHE = ${JSON.stringify(cacheName)};
const FILES = ${JSON.stringify(precache)};

// Take over as soon as the new version is cached; the page decides when to reload (pwa.js).
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('message', (e) => { if (e.data === 'skipWaiting') self.skipWaiting(); });

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('blam-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

// App files: cache first (works offline). Other origins (price APIs) are never intercepted.
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).catch(() => caches.match('./'))));
});
`);

// Site root: deliberately empty, so the app is only reachable at its own address.
fs.writeFileSync(path.join(outRoot, 'index.html'), '<!doctype html><meta charset="utf-8"><meta name="robots" content="noindex"><title>Not found</title><p>Nothing here.</p>\n');
fs.writeFileSync(path.join(outRoot, '404.html'), '<!doctype html><meta charset="utf-8"><meta name="robots" content="noindex"><title>Not found</title><p>Nothing here.</p>\n');
fs.writeFileSync(path.join(outRoot, '.nojekyll'), '');
fs.writeFileSync(path.join(outRoot, 'robots.txt'), 'User-agent: *\nDisallow: /\n');

console.log(`Built BLAM ${pkg.version} web app -> dist-web/${slug}/ (${files.length} files, cache ${cacheName})`);
